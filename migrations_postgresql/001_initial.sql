CREATE TABLE IF NOT EXISTS users(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('admin','usuario')),
    first_name TEXT NOT NULL DEFAULT '',
    last_name TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_users_email
ON users(lower(email)) WHERE email <> '';

CREATE TABLE IF NOT EXISTS login_attempts(
    key TEXT PRIMARY KEY,
    failures INTEGER NOT NULL,
    first_failed_at TEXT NOT NULL,
    locked_until TEXT
);

CREATE TABLE IF NOT EXISTS quotes(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number TEXT UNIQUE NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT NOT NULL,
    last_user_edit_at TEXT NOT NULL,
    data TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    fingerprint TEXT,
    workflow_status TEXT NOT NULL DEFAULT 'borrador',
    approved_by BIGINT REFERENCES users(id),
    approved_at TEXT,
    approved_version INTEGER,
    sent_at TEXT,
    request_status TEXT NOT NULL DEFAULT 'registrada',
    estimator_id BIGINT REFERENCES users(id),
    taken_at TEXT,
    due_date TEXT,
    correlative BIGINT
);

CREATE INDEX IF NOT EXISTS ix_quotes_owner ON quotes(owner_id);
CREATE INDEX IF NOT EXISTS ix_quotes_fingerprint ON quotes(fingerprint);
CREATE INDEX IF NOT EXISTS ix_quotes_request_status
ON quotes(request_status,created_at);
CREATE INDEX IF NOT EXISTS ix_quotes_estimator
ON quotes(estimator_id,request_status,created_at);
CREATE INDEX IF NOT EXISTS idx_quotes_request_due
ON quotes(request_status,due_date,created_at);
CREATE UNIQUE INDEX IF NOT EXISTS ux_quotes_correlative
ON quotes(correlative) WHERE correlative IS NOT NULL;

CREATE TABLE IF NOT EXISTS audit(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT REFERENCES quotes(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id),
    action TEXT,
    at TEXT,
    before TEXT,
    after TEXT
);

CREATE TABLE IF NOT EXISTS import_batches(
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT NOT NULL,
    source_name TEXT NOT NULL,
    rows TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_import_batches_user ON import_batches(user_id);

CREATE TABLE IF NOT EXISTS quote_estimators(
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS quote_commercial(
    quote_id BIGINT PRIMARY KEY REFERENCES quotes(id) ON DELETE CASCADE,
    currency TEXT NOT NULL DEFAULT 'CLP' CHECK(currency IN ('CLP','USD','EUR')),
    global_discount TEXT NOT NULL DEFAULT '0',
    tax_percent TEXT NOT NULL DEFAULT '0',
    validity_days INTEGER NOT NULL DEFAULT 15,
    payment_terms TEXT NOT NULL DEFAULT '',
    notes TEXT NOT NULL DEFAULT '',
    subtotal TEXT NOT NULL DEFAULT '0',
    discount_total TEXT NOT NULL DEFAULT '0',
    tax_total TEXT NOT NULL DEFAULT '0',
    total TEXT NOT NULL DEFAULT '0',
    updated_at TEXT NOT NULL,
    delivery_time TEXT NOT NULL DEFAULT '',
    supply_scope TEXT NOT NULL DEFAULT '',
    profit_percent TEXT NOT NULL DEFAULT '',
    profit_usd TEXT NOT NULL DEFAULT '',
    shared_user_id BIGINT REFERENCES users(id),
    shared_percent TEXT NOT NULL DEFAULT '',
    technical_support_user_id BIGINT REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS ix_quote_commercial_shared_user
ON quote_commercial(shared_user_id);
CREATE INDEX IF NOT EXISTS ix_quote_commercial_technical_support
ON quote_commercial(technical_support_user_id);

CREATE TABLE IF NOT EXISTS quote_items(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    kind TEXT NOT NULL CHECK(kind IN ('producto','servicio')),
    description TEXT NOT NULL,
    quantity TEXT NOT NULL,
    unit_price TEXT NOT NULL,
    discount_percent TEXT NOT NULL DEFAULT '0',
    line_total TEXT NOT NULL,
    details TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_quote_items_quote
ON quote_items(quote_id,position);

CREATE TABLE IF NOT EXISTS quote_versions(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    version INTEGER NOT NULL,
    created_at TEXT NOT NULL,
    user_id BIGINT REFERENCES users(id),
    data TEXT NOT NULL,
    commercial_data TEXT NOT NULL,
    items_data TEXT NOT NULL,
    UNIQUE(quote_id,version)
);

CREATE TABLE IF NOT EXISTS quote_comments(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id),
    body TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_quote_comments_quote
ON quote_comments(quote_id,id);

CREATE TABLE IF NOT EXISTS quote_attachments(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id),
    original_name TEXT NOT NULL,
    stored_name TEXT UNIQUE NOT NULL,
    mime_type TEXT NOT NULL,
    size BIGINT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_quote_attachments_quote
ON quote_attachments(quote_id,id);

CREATE TABLE IF NOT EXISTS quote_deliveries(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    attachment_id BIGINT NOT NULL UNIQUE
        REFERENCES quote_attachments(id) ON DELETE CASCADE,
    delivered_by BIGINT NOT NULL REFERENCES users(id),
    delivered_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_quote_deliveries_quote
ON quote_deliveries(quote_id,delivered_at DESC);

CREATE TABLE IF NOT EXISTS quote_number_sequence(
    id INTEGER PRIMARY KEY CHECK(id = 1),
    current_value BIGINT NOT NULL CHECK(current_value >= 0)
);
INSERT INTO quote_number_sequence(id,current_value)
VALUES(1,0) ON CONFLICT(id) DO NOTHING;

CREATE TABLE IF NOT EXISTS catalog_entries(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK(kind IN ('area','fabrica')),
    value TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)),
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_catalog_entries_kind_value
ON catalog_entries(kind,lower(value));
CREATE INDEX IF NOT EXISTS ix_catalog_entries_kind_active
ON catalog_entries(kind,active,value);
